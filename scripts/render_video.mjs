/**
 * render_video.mjs — turn the React stage into a final MP4 for Shorts/Reels/TikTok.
 *
 * Pipeline:
 *   1. vite build + vite preview   (production bundle, no HMR)
 *   2. puppeteer at exactly 1080x1920 — for every frame: window.__seek(t),
 *      wait for the committed-render signal, screenshot
 *   3. ffmpeg (ffmpeg-static) — JPEG frames + the act MP3s (delayed to their
 *      manifest positions) + SFX + an optional ducked music bed → a temporary
 *      WAV; that WAV is measured and normalized to −14 LUFS (two-pass loudnorm)
 *      and muxed into an H.264/AAC MP4 with faststart.
 *
 * Usage:
 *   bun scripts/render_video.mjs                 # full render
 *   bun scripts/render_video.mjs --max-frames 90 # smoke test (first frames only)
 *   bun scripts/render_video.mjs --keep-frames   # don't delete frames/ afterwards
 *   bun scripts/render_video.mjs --preset slow --crf 16
 *   bun scripts/render_video.mjs --no-bed --no-loudnorm  # reproduce old audio
 *   bun scripts/render_video.mjs --pre-limit             # limiter before loudnorm (peak-heavy mixes)
 *
 * Music bed: shared-assets/sfx/music_bed.wav, generated by scripts/synth_bed.py.
 * Missing bed = silent skip (no failure). Ducking is sidechain against the voice+SFX mix.
 * Per-episode scene.json may set voiceProcess (voice EQ/comp before adelay) and
 * bedGainDb (default -8). SFX events may set rate for deterministic pitch variation.
 */
import { spawn } from 'node:child_process'
import net from 'node:net'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import puppeteer from 'puppeteer'
import ffmpegPath from 'ffmpeg-static'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const FRAMES_DIR = path.join(ROOT, 'frames')
const OUT_DIR = path.join(ROOT, 'output')
const SFX_DIR = path.join(ROOT, 'shared-assets', 'sfx')

const argv = process.argv.slice(2)
const flag = (name) => argv.includes(`--${name}`)
const opt = (name, fallback) => {
  const i = argv.indexOf(`--${name}`)
  return i >= 0 && argv[i + 1] ? argv[i + 1] : fallback
}
const EPISODE = opt('episode', 'milkyway')
const defaultManifest =
  {
    milkyway: 'public/audio/milkyway/metadata.json',
    'url-explainer': 'public/audio/manifest.json',
    'space-sound': 'public/audio/space-sound/metadata.json',
    'minecraft-edge': 'public/audio/minecraft-edge/metadata.json',
  }[EPISODE] ?? `public/audio/${EPISODE}/metadata.json`
const MANIFEST_PATH = path.join(
  ROOT,
  opt(
    'manifest',
    defaultManifest,
  ),
)
const AUDIO_DIR = path.join(ROOT, 'public', 'audio')
const EPISODE_AUDIO_DIR = fs.existsSync(path.join(AUDIO_DIR, EPISODE))
  ? path.join(AUDIO_DIR, EPISODE)
  : AUDIO_DIR
const SCENE_PATH = path.join(ROOT, 'episodes', EPISODE, 'scene.json')
const SCENE = fs.existsSync(SCENE_PATH) ? JSON.parse(fs.readFileSync(SCENE_PATH, 'utf8')) : {}
const VOICE_PROCESS = SCENE.voiceProcess === true

const getFreePort = () =>
  new Promise((resolve, reject) => {
    const srv = net.createServer()
    srv.once('error', reject)
    srv.listen(0, () => {
      const port = srv.address().port
      srv.close(() => resolve(port))
    })
  })
const PREVIEW_PORT = await getFreePort()

/* ---------------- args ---------------- */
const MAX_FRAMES = Number(opt('max-frames', '0')) || Infinity
const KEEP_FRAMES = flag('keep-frames')
const NO_BED = flag('no-bed')
const NO_LOUDNORM = flag('no-loudnorm')
// Some mixes have a high true-peak-to-integrated ratio; loudnorm's linear path
// then falls back to dynamic and overshoots the -14 LUFS target. A light
// limiter before both passes makes the two-pass result land on target.
const NORM_PREFIX = flag('pre-limit') ? 'alimiter=limit=0.5,' : ''
// bed WAV peaks at -18 dBFS / -25.3 LUFS; -8 dB puts it ~-33 LUFS in gaps
// (above the -35 dB silence gate) and ~26 dB under the ducked voice.
const BED_GAIN_DB = Number(opt('bed-gain', String(SCENE.bedGainDb ?? -8)))
const BED_PATH = path.join(SFX_DIR, 'music_bed.wav')
const USE_BED = !NO_BED && fs.existsSync(BED_PATH)
const PRESET = opt('preset', 'medium')
const CRF = opt('crf', '18')
const OUT_NAME = opt('out', `${EPISODE}-1080x1920.mp4`)
const PREVIEW_URL = `http://127.0.0.1:${PREVIEW_PORT}`
const RECORD_URL = `${PREVIEW_URL}/episode?record=1${EPISODE !== 'milkyway' ? `&episode=${EPISODE}` : ''}`

const log = (...args) => console.log('[render]', ...args)

const run = (cmd, args) =>
  new Promise((resolve, reject) => {
    const child = spawn(cmd, args, { cwd: ROOT, stdio: ['ignore', 'inherit', 'inherit'] })
    child.on('exit', (code) => (code === 0 ? resolve() : reject(new Error(`${cmd} exited with ${code}`))))
  })

/** like run(), but returns stdout+stderr (loudnorm prints its JSON to stderr) */
const runCapture = (cmd, args) =>
  new Promise((resolve, reject) => {
    const child = spawn(cmd, args, { cwd: ROOT, stdio: ['ignore', 'pipe', 'pipe'] })
    let text = ''
    child.stdout.on('data', (d) => { text += String(d) })
    child.stderr.on('data', (d) => { text += String(d) })
    child.on('exit', (code) => (code === 0 ? resolve(text) : reject(new Error(`${cmd} exited with ${code}`))))
  })

const main = async () => {
  /* ---------------- 0. manifest ---------------- */
  if (!fs.existsSync(MANIFEST_PATH)) {
    throw new Error(`manifest not found at ${MANIFEST_PATH}\n   expected ${'public/audio/' + EPISODE + '/metadata.json'} (or pass --manifest <path>)`)
  }
  const manifest = JSON.parse(fs.readFileSync(MANIFEST_PATH, 'utf8'))
  const { width, height, fps, totalDuration } = manifest
  const totalFrames = Math.round(totalDuration * fps)
  const frameCount = Math.min(totalFrames, MAX_FRAMES)
  log(`"${manifest.title}" — ${totalDuration.toFixed(2)}s, ${width}x${height} @${fps}fps`)
  log(`${frameCount} frames to capture${MAX_FRAMES !== Infinity ? ' (smoke test)' : ''}`)

  /* ---------------- 1. build + preview ---------------- */
  log('building production bundle…')
  await run(process.execPath, [path.join(ROOT, 'node_modules/vite/bin/vite.js'), 'build'])

  log(`starting preview server on :${PREVIEW_PORT}…`)
  const vite = spawn(
    process.execPath,
    [path.join(ROOT, 'node_modules/vite/bin/vite.js'), 'preview', '--port', String(PREVIEW_PORT), '--strictPort', '--host', '127.0.0.1'],
    { cwd: ROOT, stdio: ['ignore', 'pipe', 'pipe'] },
  )
  vite.stderr.on('data', (d) => process.stderr.write(d))
  vite.stdout.on('data', (d) => process.stdout.write(d))

  const waitForServer = async () => {
    const deadline = Date.now() + 180_000
    while (Date.now() < deadline) {
      try {
        const res = await fetch(`${PREVIEW_URL}/`)
        if (res.ok) return
      } catch {
        /* not up yet */
      }
      await new Promise((r) => setTimeout(r, 400))
    }
    throw new Error(`vite preview server did not start within 180s (check port ${PREVIEW_PORT})`)
  }

  try {
    await waitForServer()

    /* ---------------- 2. frame capture ---------------- */
    fs.rmSync(FRAMES_DIR, { recursive: true, force: true })
    fs.mkdirSync(FRAMES_DIR, { recursive: true })

    const browser = await puppeteer.launch({
      headless: true,
      args: [
        '--no-sandbox',
        '--disable-setuid-sandbox',
        // deterministic raster output — SwiftShader software rendering
        '--disable-gpu',
        `--window-size=${width},${height}`,
      ],
    })
    const page = await browser.newPage()
    await page.setViewport({ width, height, deviceScaleFactor: 1 })
    await page.goto(RECORD_URL, { waitUntil: 'domcontentloaded', timeout: 60_000 })
    await page.waitForFunction('window.__ready === true', { timeout: 30_000 })

    const t0 = Date.now()
    for (let i = 0; i < frameCount; i++) {
      const t = i / fps
      await page.evaluate((tt) => window.__seek?.(tt), t)
      await page.waitForFunction((tt) => window.__committedFrame === tt, {}, t)
      const file = path.join(FRAMES_DIR, `frame_${String(i + 1).padStart(6, '0')}.jpg`)
      await page.screenshot({ path: file, type: 'jpeg', quality: 92 })
      if ((i + 1) % 60 === 0 || i + 1 === frameCount) {
        const pct = (((i + 1) / frameCount) * 100).toFixed(1)
        const elapsed = ((Date.now() - t0) / 1000).toFixed(1)
        log(`frames ${i + 1}/${frameCount} (${pct}%)  ${elapsed}s elapsed`)
      }
    }
    await browser.close()

    /* ---------------- 2b. SFX events (optional episodes/<slug>/sfx.json) ---------------- */
    const SFX_PATH = path.join(ROOT, 'episodes', EPISODE, 'sfx.json')
    const sfxEvents = []
    if (fs.existsSync(SFX_PATH)) {
      try {
        const parsed = JSON.parse(fs.readFileSync(SFX_PATH, 'utf8'))
        for (const e of Array.isArray(parsed?.events) ? parsed.events : []) {
          const file = path.basename(String(e?.file ?? ''))
          const full = path.join(SFX_DIR, file)
          const t = Number(e?.t)
          const gainDb = Number.isFinite(Number(e?.gainDb)) ? Number(e.gainDb) : -18
          const rate = Number.isFinite(Number(e?.rate)) && Number(e.rate) > 0 ? Number(e.rate) : 1
          if (!file || !Number.isFinite(t) || t < 0) { log(`sfx: skipping malformed event ${JSON.stringify(e)}`); continue }
          if (!fs.existsSync(full)) { log(`sfx: missing file shared-assets/sfx/${file} — skipping`); continue }
          sfxEvents.push({ file, full, t, gainDb, rate })
        }
        if (sfxEvents.length) log(`sfx: ${sfxEvents.length} event(s) <- ${path.relative(ROOT, SFX_PATH)}`)
      } catch (err) {
        log(`sfx: sfx.json unreadable, continuing without SFX (${err.message})`)
      }
    }

    /* ---------------- 3a. mix the audio to a temporary WAV ---------------- */
    fs.mkdirSync(OUT_DIR, { recursive: true })
    const outPath = path.join(OUT_DIR, OUT_NAME)
    const mixWav = path.join(OUT_DIR, `.${EPISODE}-mix.wav`)
    const framePattern = path.join(FRAMES_DIR, 'frame_%06d.jpg')

    // voice acts are delayed to their manifest positions; SFX to their beat map.
    // apad keeps the mix alive to the full timeline so -shortest cannot cut the tail.
    // NB: this ffmpeg call has audio inputs only — input 0 is the first act,
    // not the frame pattern (different numbering from the final encode below).
    const delays = manifest.acts.map((a) => Math.round(a.start * 1000))
    const voiceCount = manifest.acts.length
    // Voice processing is opt-in per episode (scene.json "voiceProcess": true) and runs
    // before adelay, so WordBoundary timestamps are not moved.
    const voiceFx = VOICE_PROCESS
      ? 'highpass=f=80,acompressor=threshold=0.125:ratio=3:attack=5:release=80:makeup=2,equalizer=f=3500:t=q:w=1:g=2,'
      : ''
    const voiceBranches = manifest.acts.map((_, i) => `[${i}:a]${voiceFx}adelay=${delays[i]}:all=1[a${i}]`)
    const sfxBranches = sfxEvents.map((e, k) => {
      const rateFx = e.rate !== 1 ? `asetrate=${Math.round(48000 * e.rate)},aresample=48000,` : ''
      return `[${voiceCount + k}:a]${rateFx}adelay=${Math.round(e.t * 1000)}:all=1,volume=${e.gainDb}dB[s${k}]`
    })
    const mixRefs = [...manifest.acts.map((_, i) => `[a${i}]`), ...sfxEvents.map((_, k) => `[s${k}]`)]
    const voiceFilter =
      [...voiceBranches, ...sfxBranches].join(';') +
      `;${mixRefs.join('')}amix=inputs=${mixRefs.length}:normalize=0,apad=whole_dur=${totalDuration}[voice]`

    const audioInputs = [
      ...manifest.acts.flatMap((a) => ['-i', path.join(EPISODE_AUDIO_DIR, a.file)]),
      ...sfxEvents.flatMap((e) => ['-i', e.full]),
    ]
    let mixFilter = voiceFilter
    if (USE_BED) {
      const bedIdx = voiceCount + sfxEvents.length
      mixFilter += `;[${bedIdx}:a]atrim=duration=${totalDuration},asetpts=PTS-STARTPTS,volume=${BED_GAIN_DB}dB[bedQuiet]`
      // a label can feed only one filter — split voice into sidechain + final mix
      mixFilter += ';[voice]asplit=2[voiceSc][voiceMix]'
      // bed is the main input, voice+SFX is the sidechain: it dips under speech
      mixFilter += ';[bedQuiet][voiceSc]sidechaincompress=threshold=0.04:ratio=6:attack=25:release=350:makeup=1[bedDucked]'
      mixFilter += `;[voiceMix][bedDucked]amix=inputs=2:normalize=0,apad=whole_dur=${totalDuration},atrim=duration=${totalDuration}[aout]`
    } else {
      mixFilter += ';[voice]anull[aout]'
    }

    log(`audio: ${voiceCount} voice act(s), ${sfxEvents.length} SFX event(s), bed ${USE_BED ? `on (${BED_GAIN_DB} dB, ducked)` : 'off'}, voice chain ${VOICE_PROCESS ? 'on' : 'off'}`)
    await run(ffmpegPath, [
      '-y', '-hide_banner', '-loglevel', 'error',
      ...audioInputs,
      // loop the deterministic 48 s bed so long-form episodes never run out of floor
      ...(USE_BED ? ['-stream_loop', '-1', '-i', BED_PATH] : []),
      '-filter_complex', mixFilter,
      '-map', '[aout]',
      '-c:a', 'pcm_s16le', '-ar', '48000', '-ac', '2', mixWav,
    ])

    /* ---------------- 3b. two-pass loudnorm to −14 LUFS ---------------- */
    let normFilter = NO_LOUDNORM ? 'anull' : NORM_PREFIX + 'loudnorm=I=-14:TP=-1.5:LRA=7'
    if (!NO_LOUDNORM) {
      log('audio: pass 1/2 — measuring integrated loudness…')
      const measured = await runCapture(ffmpegPath, [
        '-hide_banner', '-nostats', '-i', mixWav,
        '-af', NORM_PREFIX + 'loudnorm=I=-14:TP=-1.5:LRA=7:print_format=json',
        '-f', 'null', '-',
      ])
      const json = measured.match(/\{\s*"input_i"[\s\S]*?\}/)?.[0]
      if (json) {
        const m = JSON.parse(json)
        normFilter =
          NORM_PREFIX + 'loudnorm=I=-14:TP=-1.5:LRA=7' +
          `:measured_I=${m.input_i}:measured_TP=${m.input_tp}:measured_LRA=${m.input_lra}` +
          `:measured_thresh=${m.input_thresh}:offset=${m.target_offset}:linear=true:print_format=summary`
        log(`audio: measured ${m.input_i} LUFS / ${m.input_tp} dBTP → linear normalize`)
      } else {
        log('audio: loudnorm JSON missing — using dynamic single-pass instead')
      }
    } else {
      log('audio: loudnorm disabled by --no-loudnorm')
    }

    /* ---------------- 3c. encode the MP4 ---------------- */
    const ffmpegArgs = [
      '-y',
      '-thread_queue_size', '512',
      '-framerate', String(fps),
      '-i', framePattern,
      '-i', mixWav,
      '-filter_complex', `[1:a]${normFilter}[aout]`,
      '-map', '0:v:0',
      '-map', '[aout]',
      '-c:v', 'libx264',
      '-preset', PRESET,
      '-crf', CRF,
      '-pix_fmt', 'yuv420p',
      '-profile:v', 'high',
      '-level', '4.0',
      '-r', String(fps),
      '-c:a', 'aac',
      '-b:a', '192k',
      '-ar', '48000',
      '-ac', '2',
      '-movflags', '+faststart',
      '-shortest',
      outPath,
    ]

    log('encoding MP4 (libx264)…')
    await run(ffmpegPath, ffmpegArgs)

    const sizeMB = (fs.statSync(outPath).size / 1024 / 1024).toFixed(1)
    log(`done → ${outPath}  (${sizeMB} MB)`)

    if (!KEEP_FRAMES) {
      fs.rmSync(FRAMES_DIR, { recursive: true, force: true })
      fs.rmSync(mixWav, { force: true })
      log('frames/ + temp mix cleaned up (use --keep-frames to keep them)')
    } else {
      log(`frames kept in ${FRAMES_DIR}; temp mix at ${mixWav}`)
    }
  } finally {
    vite.kill()
  }
}

main().catch((err) => {
  console.error('[render] FAILED:', err instanceof Error ? err.message : err)
  console.error('frames/ kept for inspection (if any)')
  process.exit(1)
})
